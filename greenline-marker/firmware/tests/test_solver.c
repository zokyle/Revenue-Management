/* ---- double build: every vector within the tolerance of REFERENCE_VECTORS.md -------- */

GL_TEST(test_double_reproduces_every_estimator_vector)
{
    for (unsigned group = 0; group < 2u; group++) {
        double diff[F_COUNT] = { 0.0 };
        double worst = 0.0;
        int worst_field = -1;
        unsigned worst_id = 0u, n = 0u, n_fail = 0u, n_best = 0u, n_best_same = 0u, n_survey = 0u;
        for (unsigned i = 0; i < gl_vec_n_est; i++) {
            const gl_vec_est_case_t *c = &gl_vec_est[i];
            gl_vec_est_result_t r;
            est_cmp_t cmp;
            int ok;
            if (c->group != group) {
                continue;
            }
            n++;
            gl_vec64_estimate(c, GL_VEC_TOL_CASE, 0, &r);
            compare_estimate_(c, &r, aim_defined_(&c->exp), &cmp);
            ok = (r.status == ST_OK) && cmp.flags_equal && cmp.worst <= 1.0;
            if (!ok) {
                n_fail++;
                if (n_fail <= 10u) {
                    printf("    FAIL group %u case %u (%s): status %d, flags %s, worst %.3g x allowed (%s)\n",
                           group, c->id, c->mode, r.status, cmp.flags_equal ? "equal" : "DIFFER", cmp.worst,
                           (cmp.worst_field >= 0) ? FIELD_NAME[cmp.worst_field] : "-");
                }
            }
            GL_CHECK(ok);
            for (int f = 0; f < F_COUNT; f++) {
                if (cmp.diff[f] > diff[f]) {
                    diff[f] = cmp.diff[f];
                }
            }
            if (cmp.worst > worst) {
                worst = cmp.worst;
                worst_field = cmp.worst_field;
                worst_id = c->id;
            }
            if (!aim_defined_(&c->exp)) {
                /* best iterate of a failed solve: informative only */
                n_best++;
                if (excess(r.phi, c->exp.phi, 1e-6, 1, NULL) <= 1.0 && excess(r.v0, c->exp.v0, 0.0, 0, NULL) <= 1.0) {
                    n_best_same++;
                }
            }
            if (c->n_drops > 1u) {
                /* the result does not depend on where the drop at the ball sits in the array */
                gl_vec_est_result_t r2;
                gl_vec64_estimate(c, GL_VEC_TOL_CASE, 1, &r2);
                n_survey++;
                GL_CHECK(r2.status == r.status && r2.phi == r.phi && r2.v0 == r.v0 &&
                         r2.patch[0] == r.patch[0] && r2.patch[3] == r.patch[3] &&
                         r2.confidence == r.confidence && r2.n_stations == r.n_stations);
            }
        }
        printf("    double, %s: %u cases, %u outside the tolerance; worst difference %.3g x allowed "
               "(%s of case %u)\n",
               (group == 0u) ? "estimator_cases" : "fallback_estimator_cases", n, n_fail, worst,
               (worst_field >= 0) ? FIELD_NAME[worst_field] : "-", worst_id);
        printf("      largest |C - reference|:");
        for (int f = 0; f < F_COUNT; f++) {
            printf("%s %s %.1e", (f % 4 == 0) ? "\n       " : ";", FIELD_NAME[f], diff[f]);
        }
        printf("\n      %u Survey cases repeated with the ball's drop last in the array: identical\n", n_survey);
        if (n_best > 0u) {
            printf("      best iterate of the %u failed solves (not required): %u also within the tolerance\n",
                   n_best, n_best_same);
        }
        GL_CHECK_EQ(n_fail, 0);
        GL_CHECK(n > 0u);
    }
}

GL_TEST(test_double_reproduces_every_solver_vector)
{
    for (unsigned group = 0; group < 2u; group++) {
        unsigned n = 0u, n_fail = 0u, n_values = 0u, n_rolls_same = 0u, n_rolls_known = 0u, n_best = 0u,
                 n_best_same = 0u;
        double worst = 0.0;
        unsigned worst_id = 0u;
        for (unsigned i = 0; i < gl_vec_n_sol; i++) {
            const gl_vec_sol_case_t *c = &gl_vec_sol[i];
            gl_vec_sol_result_t r;
            int ok;
            double ex = 0.0, e1;
            if (c->group != group) {
                continue;
            }
            n++;
            gl_vec64_solve(c, GL_VEC_TOL_CASE, &r);
            ok = (r.status == ST_OK) && (r.solve_status == c->status);
            if (c->compare_values && ok) {
                n_values++;
                e1 = excess(r.phi, c->phi, 1e-6, 1, NULL);
                ex = (e1 > ex) ? e1 : ex;
                e1 = excess(r.v0, c->v0, 0.0, 0, NULL);
                ex = (e1 > ex) ? e1 : ex;
                e1 = excess(r.v0 * r.v0 / (2.0 * c->a_r), c->plays_like, 0.0, 0, NULL);
                ex = (e1 > ex) ? e1 : ex;
                e1 = excess(c->distance * tan(r.phi), c->aim_offset, 1e-6, 0, NULL);
                ex = (e1 > ex) ? e1 : ex;
                ok = ok && ex <= 1.0;
                if (ex > worst) {
                    worst = ex;
                    worst_id = c->id;
                }
            } else if (ok && c->status != 5u) {
                n_best++;
                if (excess(r.phi, c->phi, 1e-6, 1, NULL) <= 1.0 && excess(r.v0, c->v0, 0.0, 0, NULL) <= 1.0) {
                    n_best_same++;
                }
            }
            if (c->n_rolls >= 0) {
                n_rolls_known++;
                n_rolls_same += (r.n_rolls == (uint32_t)c->n_rolls) ? 1u : 0u;
            }
            if (!ok) {
                n_fail++;
                printf("    FAIL group %u case %u (%s): status %d / %u, reference %u, %.3g x allowed\n", group, c->id,
                       c->tag, r.status, r.solve_status, c->status, ex);
            }
            GL_CHECK(ok);
        }
        printf("    double, %s: %u cases, status equal in all but %u; values of the %u solved cases: worst "
               "difference %.3g x allowed (case %u)\n",
               (group == 0u) ? "solver_cases" : "fallback_solver_cases", n, n_fail, n_values, worst, worst_id);
        if (n_rolls_known > 0u) {
            printf("      same number of trial rolls as the reference: %u of %u; best iterate of the %u failed "
                   "solves (not required): %u within the tolerance\n",
                   n_rolls_same, n_rolls_known, n_best, n_best_same);
        }
        GL_CHECK_EQ(n_fail, 0);
    }
}

GL_TEST(test_double_reproduces_every_roll_vector)
{
    unsigned n_fail = 0u;
    double worst = 0.0;
    unsigned by_status[5] = { 0u, 0u, 0u, 0u, 0u }, holed = 0u;
    for (unsigned i = 0; i < gl_vec_n_roll; i++) {
        const gl_vec_roll_case_t *c = &gl_vec_roll[i];
        gl_vec_roll_result_t r;
        double d = 0.0, e1;
        int ok;
        gl_vec64_roll(c, &r);
        ok = (r.status == ST_OK) && r.roll_status == c->status && r.captured == c->captured &&
             r.crossed == c->crossed && r.side == c->side && r.n_steps == c->n_steps;
        e1 = fabs(r.t_end - c->t_end);
        d = (e1 > d) ? e1 : d;
        e1 = hypot(r.stop_xy[0] - c->stop_xy[0], r.stop_xy[1] - c->stop_xy[1]);
        d = (e1 > d) ? e1 : d;
        e1 = fabs(r.delta - c->delta);
        d = (e1 > d) ? e1 : d;
        e1 = fabs(r.speed_at_delta - c->speed_at_delta);
        d = (e1 > d) ? e1 : d;
        e1 = fabs(r.lateral_miss - c->lateral_miss);
        d = (e1 > d) ? e1 : d;
        e1 = fabs(r.shortfall - c->shortfall);
        d = (e1 > d) ? e1 : d;
        e1 = fabs(r.path_length - c->path_length);
        d = (e1 > d) ? e1 : d;
        if (c->crossed) {
            e1 = fabs(r.lateral_at_line - c->lateral_at_line);
            d = (e1 > d) ? e1 : d;
            e1 = fabs(r.speed_at_line - c->speed_at_line);
            d = (e1 > d) ? e1 : d;
        } else {
            ok = ok && isnan(r.lateral_at_line) && isnan(r.speed_at_line);
        }
        ok = ok && d <= 1e-9;
        worst = (d > worst) ? d : worst;
        if (!ok) {
            n_fail++;
            printf("    FAIL roll %u (%s): status %d / %u (ref %u), holed %u (%u), steps %lu (%lu), diff %.3g\n",
                   c->id, c->tag, r.status, r.roll_status, c->status, r.captured, c->captured,
                   (unsigned long)r.n_steps, (unsigned long)c->n_steps, d);
        }
        GL_CHECK(ok);
        if (c->status < 5u) {
            by_status[c->status]++;
        }
        holed += c->captured;
    }
    printf("    double, roll_cases: %u rolls (stopped %u, time limit %u, out of bounds %u, stopped on capture %u; "
           "%u holed), %u differ; status, capture, side and step count exact, largest difference %.1e\n",
           gl_vec_n_roll, by_status[0], by_status[1], by_status[2], by_status[3], holed, n_fail, worst);
    GL_CHECK_EQ(n_fail, 0);
    /* the group reaches every way a roll can end */
    GL_CHECK(by_status[0] > 0u && by_status[1] > 0u && by_status[2] > 0u && by_status[3] > 0u);
    GL_CHECK(holed > 0u && holed < gl_vec_n_roll);
}

/* ---- the single-precision roll kernel against the double one ------------------------- */

static uint32_t lcg_ = 12345u;
static double lcg_uniform_(void)
{
    lcg_ = lcg_ * 1664525u + 1013904223u;
    return (double)(lcg_ >> 8) / 16777216.0;
}

/* worst differences found by test_single_precision_roll_kernel (used to print the margins) */
static double kernel_lateral_max_ = 0.0, kernel_v2_max_ = 0.0;

GL_TEST(test_single_precision_roll_kernel)
{
    /* The SAME launch rolled in both precisions, around the solution of
     * every solved vector: how far apart do the two kernels cross the hole
     * line?  This is the noise floor below which no tolerance of the
     * single-precision solver can go; the default tolerances are set a
     * factor above it (gl_solver.h) and that factor is asserted here. */
    static samples_t lat, v2;
    unsigned n_launch = 0u;
    double med, p99;
    lat.n = 0u;
    v2.n = 0u;
    for (unsigned pass = 0; pass < 2u; pass++) {
        const unsigned n_case = (pass == 0u) ? gl_vec_n_est : gl_vec_n_sol;
        for (unsigned i = 0; i < n_case; i++) {
            double coeffs[5], grain[2], dist, a_r, phi, v0;
            if (pass == 0u) {
                const gl_vec_est_case_t *c = &gl_vec_est[i];
                if (c->exp.aim_source != 0u || c->exp.solve_status != 0u) {
                    continue;
                }
                memcpy(coeffs, c->exp.patch, sizeof(coeffs));
                memcpy(grain, c->exp.grain, sizeof(grain));
                dist = c->exp.distance;
                a_r = c->exp.a_r;
                phi = c->exp.phi;
                v0 = c->exp.v0;
            } else {
                const gl_vec_sol_case_t *c = &gl_vec_sol[i];
                if (c->status != 0u) {
                    continue;
                }
                memcpy(coeffs, c->coeffs, sizeof(coeffs));
                memcpy(grain, c->grain, sizeof(grain));
                dist = c->distance;
                a_r = c->a_r;
                phi = c->phi;
                v0 = c->v0;
            }
            for (int k = 0; k < 20; k++) {
                /* both kernels are given the launch as a single-precision number */
                const float phi_f = (float)(phi + 0.02 * (lcg_uniform_() - 0.5));
                const float v0_f = (float)(v0 * (1.0 + 0.06 * lcg_uniform_()));
                float cf[5], gf[2];
                double c64[5], g64[2], l32, s32, l64, s64;
                for (int j = 0; j < 5; j++) {
                    cf[j] = (float)coeffs[j];
                    c64[j] = (double)cf[j];
                }
                gf[0] = (float)grain[0];
                gf[1] = (float)grain[1];
                g64[0] = (double)gf[0];
                g64[1] = (double)gf[1];
                if (gl_vec32_roll_patch(c64, (double)(float)dist, (double)(float)a_r, g64, (double)phi_f,
                                        (double)v0_f, &l32, &s32) &&
                    gl_vec64_roll_patch(c64, (double)(float)dist, (double)(float)a_r, g64, (double)phi_f,
                                        (double)v0_f, &l64, &s64)) {
                    add_(&lat, fabs(l32 - l64));
                    add_(&v2, fabs(s32 * s32 - s64 * s64));
                    n_launch++;
                }
            }
        }
    }
    kernel_lateral_max_ = summarise_(&lat, &med, &p99);
    printf("    %u launches rolled in single and in double precision:\n", n_launch);
    printf("      lateral position at the hole line, |single - double|: median %.2e m, 99 %% %.2e m, max %.2e m\n",
           med, p99, kernel_lateral_max_);
    kernel_v2_max_ = summarise_(&v2, &med, &p99);
    printf("      squared arrival speed, |single - double|:              median %.2e, 99 %% %.2e, max %.2e m^2/s^2\n",
           med, p99, kernel_v2_max_);
    {
        const double tol_miss = (double)GL_SOLVER_SINGLE_TOL_MISS_M;
        const double tol_g_min = 2.0 * (1.83 * 1.83 / (2.0 * 16.0 * 0.3048)) * (double)GL_SOLVER_SINGLE_TOL_PACE_M;
        printf("      single-precision tolerances: tol_miss %.0e m = %.1f x that maximum; pace tolerance as energy at "
               "Stimp 16, %.2e m^2/s^2 = %.1f x that maximum\n",
               tol_miss, tol_miss / kernel_lateral_max_, tol_g_min, tol_g_min / kernel_v2_max_);
        GL_CHECK(n_launch > 5000u);
        /* the margins the choice of the tolerances rests on */
        GL_CHECK(kernel_lateral_max_ * 5.0 <= tol_miss);
        GL_CHECK(kernel_v2_max_ * 3.0 <= tol_g_min);
    }
}

/* ---- single build: measured deviation from the reference ----------------------------- */

typedef struct {
    samples_t aim_mrad, v0_pct, aim_point_mm, lateral_mm, rollout_mm, dist_mm, cups, conf, slope, plays_mm, dz_mm;
} deviation_t;

static deviation_t dev_; /* too large for the stack */

static void deviation_add_(deviation_t *d, const gl_vec_est_case_t *c, const gl_vec_est_result_t *r)
{
    const gl_vec_expected_t *e = &c->exp;
    double lat, speed;
    add_(&d->aim_mrad, 1e3 * angle_diff(r->aim_azimuth_device, e->aim_azimuth_device));
    add_(&d->v0_pct, 100.0 * fabs(r->v0 / e->v0 - 1.0));
    add_(&d->aim_point_mm, 1e3 * fabs(r->break_m - e->break_m));
    add_(&d->dist_mm, 1e3 * fabs(r->distance - e->distance));
    add_(&d->cups, fabs(r->break_cups - e->break_cups));
    add_(&d->conf, fabs(r->confidence - e->confidence));
    add_(&d->slope, fabs(r->slope_pct - e->slope_pct));
    add_(&d->plays_mm, 1e3 * fabs(r->plays_like - e->plays_like));
    add_(&d->dz_mm, 1e3 * fabs(r->dz_hole - e->dz_hole));
    /* where does the single-precision putt go on the REFERENCE's patch?  Rolled
     * with the double-precision kernel: lateral position at the hole, and
     * how far past the hole it would roll on a flat green against the target */
    if (e->aim_source == 0u &&
        gl_vec64_roll_patch(e->patch, e->distance, e->a_r, e->grain, r->phi, r->v0, &lat, &speed)) {
        add_(&d->lateral_mm, 1e3 * fabs(lat));
        add_(&d->rollout_mm, 1e3 * fabs(speed * speed / (2.0 * e->a_r) - c->past));
    }
}

