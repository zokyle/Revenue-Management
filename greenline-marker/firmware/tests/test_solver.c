/*
 * test_solver.c - the ported estimator and aim solver against the Python
 * reference, in BOTH precisions.
 *
 *   double build (gl_vec64_*, core compiled with -DGL_SOLVER_DOUBLE)
 *       must reproduce every reference vector within the tolerance that
 *       sim/results/REFERENCE_VECTORS.md states ("How to compare");
 *   single build (gl_vec32_*, the firmware's arithmetic)
 *       cannot reach those tolerances.  It runs with the firmware's own
 *       default tolerances; its deviation from the reference is MEASURED on
 *       every vector in the units that matter and the measured bounds are
 *       asserted with a modest margin.
 *
 * The vectors (tests/solver/gl_solver_vectors.c) are generated by
 * tools/gen_vectors.py from sim/results/reference_vectors.json: 240 + 120
 * simulated reads and solver cases, and the appended fallback / status /
 * roll groups, which between them reach every aim_source and every solve
 * status.  Also here: hostile inputs (every call must return a defined
 * status and finite or explicitly flagged outputs; this test runs under the
 * address and undefined-behaviour sanitisers in `make asan`) and the bounds
 * on trial rolls and RK4 steps.
 */
