    GL_CHECK_EQ(n_tolerance, 2);
    GL_CHECK_EQ(n_equal + n_tolerance, n);
    /* every aim source and every solve status is reached in single precision too */
    for (int s = 0; s < 4; s++) {
        GL_CHECK(src32[s] > 0u);
    }
    for (int s = 0; s < 6; s++) {
        GL_CHECK(st32[s] > 0u);
    }
    GL_CHECK(nonconv32 >= 6u);
