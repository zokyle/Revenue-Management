/** Does the double build, run with the single build's tolerances, end the
 *  same way as the single build?  Then a difference from the reference
 *  comes from the tolerance, not from the arithmetic. */
static int same_outcome_at_single_tolerance_(const gl_vec_est_case_t *c, const gl_vec_est_result_t *r32)
{
    gl_vec_est_result_t r64;
    gl_vec64_estimate(c, GL_VEC_TOL_SINGLE, 0, &r64);
    return r64.status == r32->status && r64.aim_source == r32->aim_source &&
           r64.solve_status == r32->solve_status && r64.fit_converged == r32->fit_converged &&
           r64.base_hidden == r32->base_hidden && r64.flag_missing == r32->flag_missing &&
           r64.range_missing == r32->range_missing && r64.poor_horizon == r32->poor_horizon &&
           r64.used_horizon == r32->used_horizon && r64.fit_starts == r32->fit_starts;
}

