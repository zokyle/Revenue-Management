/* ---- the comparison rule of REFERENCE_VECTORS.md ------------------------------- */

static double angle_diff(double a, double b)
{
    double d = fmod(a - b, 2.0 * PI);
    if (d < 0.0) {
        d += 2.0 * PI;
    }
    return (d > PI) ? (2.0 * PI - d) : d;
}

/**
 * |c - ref| in units of the allowed difference max(1e-4 |ref|, floor):
 * <= 1 passes.  Two not-a-numbers agree, one does not.  *abs_diff (may be
 * NULL) receives |c - ref|.
 */
static double excess(double c, double ref, double floor_abs, int is_angle, double *abs_diff)
{
    double d, allowed;
    if (abs_diff != NULL) {
        *abs_diff = 0.0;
    }
    if (isnan(c) || isnan(ref)) {
        return (isnan(c) && isnan(ref)) ? 0.0 : (double)INFINITY;
    }
    d = is_angle ? angle_diff(c, ref) : fabs(c - ref);
    if (abs_diff != NULL) {
        *abs_diff = d;
    }
    if (d == 0.0) {
        return 0.0;
    }
    allowed = 1e-4 * fabs(ref);
    if (floor_abs > allowed) {
        allowed = floor_abs;
    }
    return (allowed > 0.0) ? (d / allowed) : (double)INFINITY;
}

/** Per-field maximum differences of a group of estimator cases. */
enum {
    F_PHI, F_AIM, F_V0, F_PLAYS, F_BREAK_M, F_BREAK_CUPS, F_DISTANCE, F_DIST_SIGMA, F_BEARING,
    F_SLOPE, F_FALL, F_DZ, F_CROSS_SIGMA, F_CONF, F_A_R, F_GRAIN, F_PATCH_AB, F_PATCH_CDE,
    F_LEVEL, F_TILT, F_STATION, F_RANGE, F_COST, F_COUNT
};
static const char *const FIELD_NAME[F_COUNT] = {
    "phi [rad]", "aim_azimuth_device [rad]", "v0 [m/s]", "plays_like [m]", "break_m [m]",
    "break_cups", "distance [m]", "distance_sigma [m]", "bearing [rad]", "slope_pct",
    "fall_line_azimuth [rad]", "dz_hole [m]", "cross_slope_sigma", "confidence", "a_r [m/s^2]",
    "grain", "patch a, b", "patch c, d, e [1/m]", "level_offsets [rad]", "tilt_slopes",
    "stations [m]", "range stereo / mono [m]", "fit_cost"
};

typedef struct {
    double worst;            /* largest excess of the case */
    int worst_field;
    double diff[F_COUNT];    /* largest |difference| per field */
    int flags_equal;
} est_cmp_t;

static void note_(est_cmp_t *cmp, int field, double c, double ref, double floor_abs, int is_angle)
{
    double d;
    const double ex = excess(c, ref, floor_abs, is_angle, &d);
    if (d > cmp->diff[field]) {
        cmp->diff[field] = d;
    }
    if (ex > cmp->worst) {
        cmp->worst = ex;
        cmp->worst_field = field;
    }
}

static int flags_equal_(const gl_vec_est_result_t *r, const gl_vec_expected_t *e)
{
    return r->base_hidden == e->base_hidden && r->flag_missing == e->flag_missing &&
           r->range_missing == e->range_missing && r->poor_horizon == e->poor_horizon &&
           r->used_horizon == e->used_horizon && r->fit_converged == e->fit_converged &&
           r->aim_source == e->aim_source && r->solve_status == e->solve_status &&
           r->fit_starts == e->fit_starts && r->n_stations == e->n_stations;
}

/**
 * Compare one result with the expected record.  `with_aim`: also the
 * outputs of the aim solve (not for the best iterate of a failed solve,
 * which depends on the iteration path).
 */
static void compare_estimate_(const gl_vec_est_case_t *c, const gl_vec_est_result_t *r, int with_aim,
                              est_cmp_t *cmp)
{
    const gl_vec_expected_t *e = &c->exp;
    const int straight = (c->method == 3u);
    memset(cmp, 0, sizeof(*cmp));
    cmp->worst_field = -1;
    cmp->flags_equal = flags_equal_(r, e);
    if (with_aim) {
        note_(cmp, F_PHI, r->phi, e->phi, 1e-6, 1);
        note_(cmp, F_AIM, r->aim_azimuth_device, e->aim_azimuth_device, 1e-6, 1);
        note_(cmp, F_V0, r->v0, e->v0, 0.0, 0);
        note_(cmp, F_PLAYS, r->plays_like, e->plays_like, 0.0, 0);
        note_(cmp, F_BREAK_M, r->break_m, e->break_m, 1e-6, 0);
        note_(cmp, F_BREAK_CUPS, r->break_cups, e->break_cups, 1e-5, 0);
    }
    note_(cmp, F_DISTANCE, r->distance, e->distance, 0.0, 0);
    note_(cmp, F_DIST_SIGMA, r->distance_sigma, e->distance_sigma, 0.0, 0);
    note_(cmp, F_BEARING, r->bearing, e->bearing, 1e-6, 1);
    note_(cmp, F_SLOPE, r->slope_pct, e->slope_pct, 0.0, 0);
    if (e->slope_pct > 0.01) {
        note_(cmp, F_FALL, r->fall_line_azimuth, e->fall_line_azimuth, 1e-6, 1);
    }
    note_(cmp, F_DZ, r->dz_hole, e->dz_hole, 1e-6, 0);
    note_(cmp, F_CROSS_SIGMA, r->cross_slope_sigma, e->cross_slope_sigma, 0.0, 0);
    note_(cmp, F_CONF, r->confidence, e->confidence, 1e-6, 0);
    note_(cmp, F_A_R, r->a_r, e->a_r, 0.0, 0);
    note_(cmp, F_GRAIN, r->grain[0], e->grain[0], 0.0, 0);
    note_(cmp, F_GRAIN, r->grain[1], e->grain[1], 0.0, 0);
    for (int i = 0; i < 5; i++) {
        note_(cmp, (i < 2) ? F_PATCH_AB : F_PATCH_CDE, r->patch[i], e->patch[i], (i < 2) ? 1e-7 : 1e-8, 0);
    }
    for (int i = 0; i < 2; i++) {
        note_(cmp, F_LEVEL, r->level_offsets[i], e->level_offsets[i], 1e-8, 0);
        note_(cmp, F_TILT, r->tilt_slopes[i], e->tilt_slopes[i], 1e-7, 0);
    }
    for (unsigned i = 0; i < e->n_stations && i < 4u; i++) {
        note_(cmp, F_STATION, r->stations[i], e->stations[i], 0.0, 0);
    }
    note_(cmp, F_RANGE, r->range_stereo, e->range_stereo, 0.0, 0);
    note_(cmp, F_RANGE, r->range_mono, e->range_mono, 0.0, 0);
    if (!straight) {
        note_(cmp, F_COST, r->fit_cost, e->fit_cost, 1e-6, 0);
    }
}

/** The outputs of the aim solve are defined (not the best iterate of a
 *  failed solve). */
static int aim_defined_(const gl_vec_expected_t *e)
{
    return e->aim_source != 2u;
}

/* ---- small statistics ------------------------------------------------------------- */

#define MAX_SAMPLES 8192
typedef struct {
    double v[MAX_SAMPLES];
    unsigned n;
} samples_t;

static void add_(samples_t *s, double v)
{
    if (s->n < MAX_SAMPLES) {
        s->v[s->n++] = v;
    }
}

static int cmp_double_(const void *a, const void *b)
{
    const double x = *(const double *)a, y = *(const double *)b;
    return (x > y) - (x < y);
}

/** Sorts; returns the maximum, *median and *p99 on the way. */
static double summarise_(samples_t *s, double *median, double *p99)
{
    if (s->n == 0u) {
        *median = 0.0;
        *p99 = 0.0;
        return 0.0;
    }
    qsort(s->v, s->n, sizeof(double), cmp_double_);
    *median = s->v[s->n / 2u];
    *p99 = s->v[(unsigned)((double)(s->n - 1u) * 0.99)];
    return s->v[s->n - 1u];
}

static void print_row_(const char *label, samples_t *s, double bound, const char *note)
{
    double med, p99;
    const double mx = summarise_(s, &med, &p99);
    printf("      %-44s %10.3e %10.3e %10.3e   %-9.3g %s\n", label, med, p99, mx, bound, note);
}

