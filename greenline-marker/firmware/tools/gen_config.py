#!/usr/bin/env python3
"""Generate core/gl_config.h from design/master_params.yaml.

Usage:
    gen_config.py [--check] <master_params.yaml> <output gl_config.h>

With --check nothing is written; the exit status is 1 if the existing header
differs from what would be generated (stale header), 0 otherwise.

Only numbers that the firmware needs are exported.  Every macro carries its
unit in the name.  Derived values are computed here, once, so that the C code
contains no hand-copied geometry.
"""
import sys

import yaml

# Constants that are NOT in master_params.yaml, each with its source.
LCD_PIXELS = 128              # LS013B7DH03: 128 x 128 (part number, display.md)
BALL_DIAMETER_MM = 42.67      # Rules of Golf minimum ball diameter (1.680 in)
CAM_SENSOR_COLS = 640         # OVM7692 VGA
CAM_SENSOR_ROWS = 480


def f(value):
    """Format a number as a C float literal."""
    text = repr(float(value))
    if "e" in text or "E" in text:
        return text + "f"
    if "." not in text:
        text += ".0"
    return text + "f"


def generate(params):
    env = params["envelope"]
    lcd = params["lcd"]
    cam = params["cameras"]
    prism = params["prisms"]
    base = params["base_plate"]
    ring = params["bottom_side_parts"]["grain_led_ring"]

    outer_r = float(env["outer_radius"])
    active_mm = float(lcd["active"]["dx"])
    aperture_mm = float(lcd["aperture_dia"])
    pitch_mm = active_mm / LCD_PIXELS
    aperture_px = aperture_mm / pitch_mm
    clip_dia_px = int(aperture_px)          # floor: stay inside the aperture
    ball_r = BALL_DIAMETER_MM / 2.0
    ball_y_mm = outer_r + ball_r
    baseline_mm = float(cam["baseline"])
    f_px = float(cam["f_px"])
    axis_z_mm = float(prism["optical_axis_z"])

    if abs((cam["right"]["x"] - cam["left"]["x"]) - baseline_mm) > 1e-6:
        raise SystemExit("cameras.baseline disagrees with left/right x positions")
    if active_mm != float(lcd["active"]["dy"]):
        raise SystemExit("LCD active area is expected to be square")

    out = []
    w = out.append
    w("/*")
    w(" * gl_config.h - GENERATED by tools/gen_config.py from design/master_params.yaml.")
    w(" * DO NOT EDIT.  Run `make config` after changing the YAML; `make test`")
    w(" * fails if this file is stale.")
    w(" *")
    w(" * Frame: origin at the puck centre on the base plane, +x right, +y forward")
    w(" * (toward the ball / hole), +z up.  Units are in the macro names.")
    w(" */")
    w("#ifndef GL_CONFIG_H")
    w("#define GL_CONFIG_H")
    w("")
    w('#define GL_CFG_PARAMS_REV "%s"' % params["rev"])
    w("")
    w("/* ---- envelope ---- */")
    w("#define GL_CFG_OUTER_RADIUS_MM          %s" % f(outer_r))
    w("#define GL_CFG_THICKNESS_MM             %s" % f(env["thickness"]))
    w("#define GL_CFG_VISOR_FLAT_Y_MM          %s  /* outer face of the D-cut */" %
      f(env["front_flat_y_outer"]))
    w("")
    w("/* ---- display (LS013B7DH03) ---- */")
    w("#define GL_CFG_LCD_PIXELS               %d     /* per side; not in the YAML: part number */" %
      LCD_PIXELS)
    w("#define GL_CFG_LCD_ACTIVE_MM            %s" % f(active_mm))
    w("#define GL_CFG_LCD_PIXEL_PITCH_MM       %s  /* active / pixels */" % f(round(pitch_mm, 6)))
    w("#define GL_CFG_LCD_APERTURE_DIA_MM      %s" % f(aperture_mm))
    w("#define GL_CFG_LCD_APERTURE_DIA_PX_F    %s  /* aperture / pitch */" %
      f(round(aperture_px, 4)))
    w("#define GL_CFG_LCD_CLIP_DIA_PX          %d     /* floor of the above: UI clip circle */" %
      clip_dia_px)
    w("")
    w("/* ---- ball position for the aim line ---- */")
    w("/* The ball centre is taken at outer radius + ball radius ahead of the")
    w(" * marker centre on +y (ball touching the puck's outer circle).  The ball")
    w(" * diameter (%.2f mm, Rules of Golf minimum) is not in the YAML. */" % BALL_DIAMETER_MM)
    w("#define GL_CFG_BALL_RADIUS_MM           %s" % f(round(ball_r, 4)))
    w("#define GL_CFG_BALL_CENTRE_Y_MM         %s  /* %.1f + %.3f */" %
      (f(round(ball_y_mm, 4)), outer_r, ball_r))
    w("#define GL_CFG_BALL_CENTRE_Y_PX         %s  /* in LCD pixels from the screen centre */" %
      f(round(ball_y_mm / pitch_mm, 3)))
    w("")
    w("/* ---- cameras (OVM7692 + fold prism) ---- */")
    w("#define GL_CFG_CAM_SENSOR_COLS          %d" % CAM_SENSOR_COLS)
    w("#define GL_CFG_CAM_SENSOR_ROWS          %d" % CAM_SENSOR_ROWS)
    w("#define GL_CFG_CAM_F_PX                 %s" % f(f_px))
    w("#define GL_CFG_CAM_EFL_MM               %s" % f(cam["efl_mm"]))
    w("#define GL_CFG_CAM_PIXEL_UM             %s" % f(cam["pixel_um"]))
    w("#define GL_CFG_CAM_FOV_H_DEG            %s" % f(cam["fov_deg"]["h"]))
    w("#define GL_CFG_CAM_FOV_V_DEG            %s" % f(cam["fov_deg"]["v"]))
    w("#define GL_CFG_CAM_BASELINE_MM          %s" % f(baseline_mm))
    w("#define GL_CFG_CAM_BASELINE_M           %s" % f(round(baseline_mm / 1000.0, 7)))
    w("#define GL_CFG_CAM_LEFT_X_MM            %s" % f(cam["left"]["x"]))
    w("#define GL_CFG_CAM_LEFT_Y_MM            %s" % f(cam["left"]["y"]))
    w("#define GL_CFG_CAM_RIGHT_X_MM           %s" % f(cam["right"]["x"]))
    w("#define GL_CFG_CAM_RIGHT_Y_MM           %s" % f(cam["right"]["y"]))
    w("#define GL_CFG_CAM_EXIT_FACE_Y_MM       %s" % f(prism["exit_face_y"]))
    w("#define GL_CFG_CAM_AXIS_HEIGHT_MM       %s  /* optical axis above the base plane */" %
      f(axis_z_mm))
    w("#define GL_CFG_CAM_AXIS_HEIGHT_M        %s" % f(round(axis_z_mm / 1000.0, 7)))
    w("#define GL_CFG_STEREO_F_TIMES_B_PX_M    %s  /* f_px * baseline_m: disparity_px * range_m */" %
      f(round(f_px * baseline_mm / 1000.0, 6)))
    w("")
    w("/* ---- grain sensor ring (PCB underside) ---- */")
    w("#define GL_CFG_GRAIN_CENTRE_X_MM        %s" % f(ring["x"]))
    w("#define GL_CFG_GRAIN_CENTRE_Y_MM        %s" % f(ring["y"]))
    w("#define GL_CFG_GRAIN_RING_RADIUS_MM     %s" % f(ring["radius"]))
    w("#define GL_CFG_GRAIN_LED_PAIRS          %d" % int(ring["count_pairs"]))
    w("#define GL_CFG_GRAIN_OPENING_DIA_MM     %s" % f(base["grain_cavity"]["dia"]))
    w("")
    w("#endif /* GL_CONFIG_H */")
    return "\n".join(out) + "\n"


def main(argv):
    args = [a for a in argv[1:] if a != "--check"]
    check = "--check" in argv[1:]
    if len(args) != 2:
        raise SystemExit(__doc__)
    with open(args[0], "r", encoding="utf-8") as fh:
        params = yaml.safe_load(fh)
    text = generate(params)
    if check:
        try:
            with open(args[1], "r", encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            current = None
        if current != text:
            print("STALE: %s does not match %s (run `make config`)" % (args[1], args[0]))
            return 1
        return 0
    with open(args[1], "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s" % args[1])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
